import type { ScenarioResult } from "./engine";
import { COMPANY } from "./company";

export interface ReportMeta {
  siteAreaM2: number;
  frontageM: number;
  roadWidthM: number;
  density: string;
  programType: string;
  parcelSource?: "map sketch" | "manual entry" | "saved parcel";
  vertexCount?: number;
}

function reportRef(meta: ReportMeta): string {
  const d = new Date();
  const stamp = d.toISOString().slice(0, 10).replace(/-/g, "");
  return `AG-${stamp}-${meta.siteAreaM2}`;
}

function fmtDate(d = new Date()) {
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

export function buildReportText(scenarios: ScenarioResult[], meta: ReportMeta): string {
  const ref = reportRef(meta);
  const lines: string[] = [];

  lines.push("═".repeat(72));
  lines.push(COMPANY.legalName.toUpperCase());
  lines.push(COMPANY.serviceName);
  lines.push(COMPANY.tagline);
  lines.push("═".repeat(72));
  lines.push("");
  lines.push("DEVELOPMENT CAPACITY ASSESSMENT REPORT");
  lines.push(`Report reference: ${ref}`);
  lines.push(`Generated: ${fmtDate()}`);
  lines.push("");
  lines.push("— SERVICE PROVIDER —");
  lines.push(`Company:     ${COMPANY.legalName}`);
  lines.push(`Service:     ${COMPANY.serviceName}`);
  lines.push(`Website:     ${COMPANY.website}`);
  lines.push(`Email:       ${COMPANY.email}`);
  lines.push(`Telephone:   ${COMPANY.phoneDisplay}`);
  lines.push("");
  lines.push("— PARCEL SUMMARY —");
  lines.push(`Site area:        ${meta.siteAreaM2.toLocaleString()} m²`);
  lines.push(`Frontage:         ${meta.frontageM} m`);
  lines.push(`Road width:       ${meta.roadWidthM} m`);
  lines.push(`Density tier:     ${meta.density}`);
  lines.push(`Program type:     ${meta.programType.replace("_", " ")}`);
  if (meta.parcelSource) lines.push(`Input source:     ${meta.parcelSource}${meta.vertexCount ? ` (${meta.vertexCount} vertices)` : ""}`);
  lines.push(`Regulatory basis: ${COMPANY.jurisdiction}`);
  lines.push("");

  scenarios.forEach((s) => {
    lines.push("─".repeat(72));
    lines.push(`SCENARIO: ${s.scenarioLabel.toUpperCase()}`);
    lines.push("─".repeat(72));
    lines.push(`FAR applied:           ${s.far.value}  [${s.far.confidence}]`);
    if (s.far.note) lines.push(`  Note: ${s.far.note}`);
    lines.push(`Height category:       ${s.heightCategory.label}  [FACT]`);
    lines.push(`Floors:                ${s.floors}  [ESTIMATE]`);
    lines.push(`Building height:       ${s.heightM} m  [ESTIMATE]`);
    lines.push(`Footprint:             ${s.footprintM2} m²  (governing: ${s.governingConstraint})`);
    lines.push(`Achieved GFA:          ${s.achievedGFA} m² of ${s.maxRegulatedGFA} m² regulated ceiling`);
    lines.push(`Regulation utilisation: ${s.regulationUtilisationPct}%`);
    lines.push(`Open space:            ${s.openSpaceM2} m² (${s.openSpacePct}%)`);
    lines.push(`Estimated units:       ${s.units}  [ESTIMATE]`);
    lines.push(`Parking required:      ${s.parking.total} spaces  [ESTIMATE]`);
    lines.push(`Compliance status:     ${s.complianceLevel.toUpperCase()}`);
    if (s.flags.length) {
      lines.push("Compliance flags:");
      s.flags.forEach((f) => lines.push(`  • [${f.level.toUpperCase()}] ${f.message}`));
    }
    lines.push("");
  });

  lines.push("═".repeat(72));
  lines.push("DISCLAIMER");
  lines.push("═".repeat(72));
  lines.push(
    "This report is generated by the AlphaGRID regulation engine for screening and planning assistance purposes only. " +
      "Figures tagged ESTIMATE or INTERPRETED carry stated assumptions. Confirm all capacity, setback, and height " +
      "requirements against the current gazetted planning instrument before any transaction, design commitment, or " +
      "financial decision. AlphaGRID (Pvt.) Ltd accepts no liability for reliance on this document without independent verification."
  );
  lines.push("");
  lines.push(`${COMPANY.legalName} · ${COMPANY.website} · ${COMPANY.email}`);

  return lines.join("\n");
}

