export function downloadReportFile(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function downloadProfessionalReport(scenarios: ScenarioResult[], meta: ReportMeta, format: "html" | "txt" = "html") {
  const slug = `alphagrid-report-${meta.siteAreaM2}m2-${reportRef(meta)}`;
  if (format === "html") {
    downloadReportFile(buildReportHtml(scenarios, meta), `${slug}.html`, "text/html;charset=utf-8");
  } else {
    downloadReportFile(buildReportText(scenarios, meta), `${slug}.txt`, "text/plain;charset=utf-8");
  }
}

export function printProfessionalReport(scenarios: ScenarioResult[], meta: ReportMeta) {
  const html = buildReportHtml(scenarios, meta);
  const win = window.open("", "_blank", "width=900,height=700");
  if (!win) return;
  win.document.write(html);
  win.document.close();
  win.onload = () => {
    win.focus();
    win.print();
  };
}
